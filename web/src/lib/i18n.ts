export const DICTS: Record<Locale, Record<MessageKey, string>> = { tr, en, de, ru, ar };

const SPEC_KEYS = [
  "Benzin",
  "Dizel",
  "Hibrit",
  "Elektrik",
  "Otomatik",
  "Manuel",
  "Ekonomik",
  "SUV",
  "Minibüs",
  "Lüks",
] as const;

export function specLabel(locale: Locale, raw: string) {
  if ((SPEC_KEYS as readonly string[]).includes(raw)) {
    return translate(locale, `val.${raw}` as MessageKey);
  }
  return raw;
}

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>) {
  let text = DICTS[locale][key] ?? tr[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

export function parseTryAmount(price: string): number {
  const match = price.match(/([\d.,]+)/);
  if (!match) return 0;
  const raw = match[1];
  if (/€|EUR/i.test(price)) {
    const eur = parseFloat(raw.replace(/\./g, "").replace(",", "."));
    return Number.isNaN(eur) ? 0 : Math.round(eur * TRY_PER.EUR);
  }
  const n = parseFloat(raw.replace(/\./g, "").replace(",", "."));
  return Number.isNaN(n) ? 0 : n;
}

export function formatMoney(tryAmount: number, currency: Currency, locale: Locale): string {
  const loc =
    locale === "de" ? "de-DE" : locale === "tr" ? "tr-TR" : locale === "ar" ? "ar-SA" : locale === "ru" ? "ru-RU" : "en-US";
  if (currency === "TRY") {
    return `${Math.round(tryAmount).toLocaleString("tr-TR")} TL`;
  }
  const value = tryAmount / TRY_PER[currency];
  const rounded = value >= 100 ? Math.round(value) : Math.round(value * 10) / 10;
  const formatted = rounded.toLocaleString(loc, {
    minimumFractionDigits: rounded % 1 === 0 ? 0 : 1,
    maximumFractionDigits: 1,
  });
  const symbol = CURRENCIES.find((c) => c.code === currency)?.symbol ?? currency;
  return `${symbol}${formatted}`;
}

export function formatPriceIn(price: string, currency: Currency, locale: Locale): string {
  return formatMoney(parseTryAmount(price), currency, locale);
}
